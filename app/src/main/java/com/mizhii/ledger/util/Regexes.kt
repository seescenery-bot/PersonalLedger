package com.mizhii.ledger.util

/**
 * 全部正则与关键词的唯一集中地（需求文档 §0 铁律 4）。
 *
 * 修改通知文案适配时，**只改这个文件**。
 * 每一条正则在 `RegexesTest` / `NotificationParserTest` 里都有对应用例。
 */
object Regexes {

    // ── 归一化 ────────────────────────────────────────────────────────
    /** 微信合并通知的聚合前缀："[2条]" "[99条]" */
    val AGGREGATE_PREFIX = Regex("^\\[\\s*\\d+\\s*条\\s*\\]\\s*")

    /** 正文里重复出现的账号名前缀："微信支付:" "支付宝：" */
    val ACCOUNT_PREFIX = Regex("^(微信支付|微信收款助手|支付宝)\\s*[:：]\\s*")

    // ── 金额（按优先级依次尝试）────────────────────────────────────────
    /** 带货币符号：¥25.00 ￥1,280.50 */
    val AMOUNT_SYMBOL = Regex("[¥￥]\\s*(\\d{1,9}(?:,\\d{3})*(?:\\.\\d{1,2})?)")

    /** 以「元」结尾：25.00元 */
    val AMOUNT_YUAN = Regex("(\\d{1,9}(?:,\\d{3})*(?:\\.\\d{1,2})?)\\s*元")

    /** 带金额锚点词：金额：25.00 / 收款25.00 */
    val AMOUNT_ANCHORED = Regex(
        "(?:金额|收款|付款|转账|红包|到账|支付|收入|支出)\\s*[:：]?\\s*[¥￥]?\\s*(\\d{1,9}(?:\\.\\d{1,2})?)"
    )

    /** 最后兜底：任意带两位小数的数字（必须已经过语义判定才会走到这一步） */
    val AMOUNT_BARE_DECIMAL = Regex("(\\d{1,9}\\.\\d{1,2})")

    val AMOUNT_PATTERNS = listOf(AMOUNT_SYMBOL, AMOUNT_YUAN, AMOUNT_ANCHORED, AMOUNT_BARE_DECIMAL)

    /**
     * 带「金额」类标签 + 冒号的强金额：`支付金额：20.00`、`实付金额 ¥4.50`。
     * 真机样本：微信"非税支付"回执页（`支付金额：` + `20.00元` 是两个独立节点）。
     */
    val AMOUNT_LABELED = Regex(
        "(?:支付金额|实付金额|付款金额|交易金额|订单金额|金额)" +
            "\\s*[:：]\\s*[¥￥]?\\s*(\\d{1,9}(?:,\\d{3})*(?:\\.\\d{1,2})?)"
    )

    /**
     * **通道 B 专用**的强金额集合（§6.3.3 真机校准后新增）。
     *
     * 页面解析不能用通道 A 那套宽松四级回退：通知是一条短文案，而页面是一整屏文字，
     * 裸小数会把 "鸣潮3.4版本获奖了" 解析成 3.40 元（真实误报，微信首页）。
     * 因此页面只认"确定性高"的三种形态：币种符号 / 以「元」结尾 / 标签+冒号。
     */
    val AMOUNT_PATTERNS_STRICT = listOf(AMOUNT_SYMBOL, AMOUNT_YUAN, AMOUNT_LABELED)

    /**
     * 整段文本就是一个数字（可带 ¥ 或「元」）。
     * 真机里金额经常被拆成两个节点：`¥` + `23.00`（微信账单详情页）。
     */
    val AMOUNT_ONLY_NUMBER =
        Regex("^[¥￥]?\\s*(\\d{1,9}(?:,\\d{3})*(?:\\.\\d{1,2})?)\\s*元?$")

    // ── 语义关键词 ───────────────────────────────────────────────────
    /** 支出。注意真机文案是「已支付」而不是「支付成功」（§6.2.7） */
    val EXPENSE_KEYWORDS = listOf(
        "支付成功", "付款成功", "已支付", "支付完成", "付款完成",
        "购买成功", "扣款成功", "已付款", "成功付款", "消费", "支付了"
    )

    /** 收入。注意「收到」比「收到转账」更宽容：「你收到一笔转账」中间会夹字 */
    val INCOME_KEYWORDS = listOf(
        "收款成功", "成功收款", "已收款", "收到", "收款", "转入",
        "转账到账", "红包到账", "已到账", "入账",
        "收到红包", "向你付款", "向你转账", "已收钱", "转账给你"
    )

    /** 退款单独判定，且**优先于收入**（"退款到账"同时含收入词） */
    val REFUND_KEYWORDS = listOf("退款", "已退款", "退款成功", "退款到账", "退货退款", "返现")

    /**
     * 转账类收入：属于**往来款**（朋友还钱 / AA / 代收），通常不该计入"真实收入"。
     * 单独识别出来是为了给到 `transfer_in` 分类，并在统计口径上可区分。
     */
    val TRANSFER_IN_KEYWORDS = listOf(
        "收到转账", "转账到账", "转账给你", "向你转账", "转账收款", "收到一笔转账", "已收到转账"
    )

    /**
     * 收款码 / 个人收款到账：**通知里没有付款人信息**，无法区分"真实经营收入"
     * 与"朋友还钱 / 自己套现"，因此必须强制进待确认，由用户裁决一次。
     */
    val COLLECT_KEYWORDS = listOf(
        "收款到账", "收款成功", "成功收款", "已收款", "已收钱", "向你付款", "向你付钱"
    )

    /**
     * 排除词（§6.2.4）。命中即丢弃，**在抽金额之前判定**。
     *
     * ⚠️ 不要在这里放裸的「收款码」「赞赏码」「群收款」！
     * 那三者都是**收入**，排除掉就会把真实到账静默丢掉（本项目真实踩过的坑）。
     * 只排除「码的配置类」通知。
     */
    val EXCLUDE_KEYWORDS = listOf(
        "还款", "账单", "剩余", "最低", "核对", "扣款失败", "已还清", "逾期", "待还", "需还",
        "收款码已更新", "收款码已失效", "收款码更新", "设置收款码", "开通收款码", "赞赏码已",
        "待你收款", "确认收款",
        "优惠券", "验证码", "余额提醒", "登录", "账户安全", "GroupSummary", "你有一条新消息",
        // 真机样本（2026-10-29）：零钱提现是"自己的钱从零钱搬到银行卡"，既不是收入也不是支出。
        // 通知里还没有金额（`[4条]微信支付: 零钱提现已到账`），一旦放开就会被记成一笔假收入。
        "提现"
    )

    // ── 商户 / 对方（通道 B、C 用，通道 A 一般拿不到）───────────────
    val MERCHANT_PATTERNS = listOf(
        Regex("(?:商户|商家|收款方)\\s*[:：]\\s*([^\\s，。,:：]{1,20})"),
        Regex("向\\s*([^\\s，。:：]{1,20})\\s*(?:付款|支付)"),
        Regex("(?:付款给|转账给)\\s*([^\\s，。:：]{1,20})"),
        Regex("在\\s*([^\\s，。:：]{1,20})\\s*(?:消费|购买|支付)"),
        Regex("收到\\s*(?:来自\\s*)?([^\\s，。:：]{1,20})\\s*(?:的)?(?:转账|红包)"),
        Regex("([^\\s，。:：]{1,20})\\s*(?:向你|向您)\\s*(?:付款|转账)")
    )

    /** 交易单号（通道 B、C 用） */
    val EXTERNAL_NO = Regex("(?:交易单号|商户单号|订单号|交易订单号)\\s*[:：]?\\s*([A-Za-z0-9]{8,40})")

    // ── 标题白名单（§6.2.2）─────────────────────────────────────────
    /** 微信支付通知没有独立渠道，与聊天消息共用 message_channel_*，只能按 title 过滤 */
    val WECHAT_PAY_TITLES = setOf("微信支付", "微信收款助手", "微信支付凭证")

    const val ALIPAY_PAY_TITLE_KEYWORD = "支付宝"
}
